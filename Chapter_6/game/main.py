import hardware
import engine

INITIAL_LEVEL = "home"
INITIAL_SPAWN = (1, 1)

display = hardware.detect()
if display.neopixel is not None:
    display.neopixel.fill((0, 3, 5))

game = engine.Game(display)
game.load_level(INITIAL_LEVEL)
game.set_hero_xy(*INITIAL_SPAWN)
game.play()
